create or replace function public.touch_competition_application_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := timezone('utc', now());

  if new.status is distinct from old.status then
    new.status_changed_at := timezone('utc', now());
  end if;

  return new;
end;
$$;

drop trigger if exists competition_applications_touch_updated_at on public.competition_applications;
create trigger competition_applications_touch_updated_at
before update on public.competition_applications
for each row execute procedure public.touch_competition_application_updated_at();

create or replace function public.log_competition_application_status_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into public.competition_application_events (
      application_id,
      from_status,
      to_status,
      actor_id,
      actor_role,
      actor_name,
      public_comment,
      created_at
    )
    values (
      new.id,
      case when tg_op = 'INSERT' then null else old.status end,
      new.status,
      auth.uid(),
      public.current_crm_role(),
      new.status_changed_by,
      nullif(trim(coalesce(new.comment, '')), ''),
      coalesce(new.status_changed_at, timezone('utc', now()))
    );
  end if;

  return new;
end;
$$;

drop trigger if exists competition_applications_log_status_event on public.competition_applications;
create trigger competition_applications_log_status_event
after insert or update on public.competition_applications
for each row execute procedure public.log_competition_application_status_event();

