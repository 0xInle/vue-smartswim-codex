create policy "Allow authenticated users to insert own competition applications"
on public.competition_applications
for insert
to authenticated
with check (
  owner_user_id = auth.uid()
  and nullif(trim(owner_email), '') is not null
  and nullif(trim(competition_slug), '') is not null
  and nullif(trim(competition_name), '') is not null
  and nullif(trim(stage_id), '') is not null
  and participant_kind in ('owner', 'athlete')
  and registration_kind in ('individual', 'relay', 'long-distance')
  and status = 'submitted'
);

create policy "Allow authenticated users to read own competition applications"
on public.competition_applications
for select
to authenticated
using (
  owner_user_id = auth.uid()
  or public.current_crm_role() = 'admin'
);

create policy "Allow authenticated users to withdraw own competition applications"
on public.competition_applications
for update
to authenticated
using (
  owner_user_id = auth.uid()
  and status in ('submitted', 'reviewing', 'needs_fix', 'approved', 'payment_pending')
)
with check (
  owner_user_id = auth.uid()
  and status = 'withdrawn'
);

create policy "Allow admin read competition applications"
on public.competition_applications
for select
to authenticated
using (public.current_crm_role() = 'admin');

create policy "Allow admin update competition applications"
on public.competition_applications
for update
to authenticated
using (public.current_crm_role() = 'admin')
with check (public.current_crm_role() = 'admin');

create policy "Allow admin delete competition applications"
on public.competition_applications
for delete
to authenticated
using (public.current_crm_role() = 'admin');

create policy "Allow authenticated users to delete own withdrawn competition applications"
on public.competition_applications
for delete
to authenticated
using (
  owner_user_id = auth.uid()
  and status = 'withdrawn'
);

