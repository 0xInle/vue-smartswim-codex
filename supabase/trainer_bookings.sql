create table if not exists public.trainer_bookings (
  id bigint generated by default as identity primary key,
  trainer_id text not null,
  trainer_name text not null,
  client_user_id uuid references auth.users (id) on delete set null,
  client_first_name text not null,
  client_last_name text not null,
  client_phone text not null,
  client_phone_normalized text,
  client_email text not null,
  client_email_normalized text,
  preferred_date date not null,
  preferred_time time not null,
  training_format text not null default 'individual',
  comment text,
  status text not null default 'new',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint trainer_bookings_status_check
    check (status in ('new', 'contacted', 'confirmed', 'cancelled', 'completed')),
  constraint trainer_bookings_format_check
    check (training_format in ('individual', 'group'))
);

