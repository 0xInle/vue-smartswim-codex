create or replace function public.normalize_email(input_email text)
returns text
language sql
set search_path = public
immutable
as $$
  select lower(trim(coalesce(input_email, '')));
$$;

create or replace function public.touch_trainer_booking_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

create or replace function public.prepare_trainer_booking()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  duplicate_slot_exists boolean;
begin
  new.trainer_id := trim(coalesce(new.trainer_id, ''));
  new.trainer_name := trim(coalesce(new.trainer_name, ''));
  new.client_first_name := trim(coalesce(new.client_first_name, ''));
  new.client_last_name := trim(coalesce(new.client_last_name, ''));
  new.client_phone := trim(coalesce(new.client_phone, ''));
  new.client_email := trim(coalesce(new.client_email, ''));
  new.comment := nullif(trim(coalesce(new.comment, '')), '');
  new.client_phone_normalized := public.normalize_phone(new.client_phone);
  new.client_email_normalized := public.normalize_email(new.client_email);

  if new.trainer_id = '' or new.trainer_name = '' then
    raise exception 'Не удалось определить тренера для записи.';
  end if;

  if new.client_first_name = '' or new.client_last_name = '' then
    raise exception 'Укажите имя и фамилию.';
  end if;

  if new.client_phone_normalized = '' then
    raise exception 'Укажите корректный номер телефона.';
  end if;

  if new.client_email_normalized = '' then
    raise exception 'Укажите корректную электронную почту.';
  end if;

  if
    new.preferred_date < current_date
    and (
      TG_OP = 'INSERT'
      or new.preferred_date is distinct from old.preferred_date
    )
  then
    raise exception 'Дата записи не может быть в прошлом.';
  end if;

  select exists (
    select 1
    from public.trainer_bookings as trainer_bookings
    where trainer_bookings.id <> coalesce(new.id, -1)
      and trainer_bookings.trainer_id = new.trainer_id
      and trainer_bookings.client_phone_normalized = new.client_phone_normalized
      and trainer_bookings.preferred_date = new.preferred_date
      and trainer_bookings.preferred_time = new.preferred_time
  )
  into duplicate_slot_exists;

  if duplicate_slot_exists then
    raise exception 'Запись к этому тренеру на выбранные дату и время уже существует.';
  end if;

  return new;
end;
$$;

