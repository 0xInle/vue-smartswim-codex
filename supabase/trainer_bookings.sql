create or replace function public.current_crm_email()
returns text
language sql
stable
set search_path = public
as $$
  select lower(trim(coalesce(auth.jwt() ->> 'email', '')));
$$;

grant execute on function public.current_crm_email() to authenticated;
revoke execute on function public.current_crm_email() from public, anon;

create policy "Allow public insert trainer bookings"
on public.trainer_bookings
for insert
to anon, authenticated
with check (
  nullif(trim(trainer_id), '') is not null
  and nullif(trim(trainer_name), '') is not null
  and nullif(trim(client_first_name), '') is not null
  and nullif(trim(client_last_name), '') is not null
  and nullif(trim(client_phone), '') is not null
  and char_length(public.normalize_phone(client_phone)) between 10 and 15
  and nullif(trim(client_email), '') is not null
  and preferred_date >= current_date
  and preferred_time is not null
  and training_format in ('individual', 'group')
  and status = 'new'
);

create policy "Allow admin insert trainer bookings"
on public.trainer_bookings
for insert
to authenticated
with check (public.current_crm_role() = 'admin');

create policy "Allow authenticated own read trainer bookings"
on public.trainer_bookings
for select
to authenticated
using (
  public.current_crm_role() = 'admin'
  or auth.uid() = client_user_id
  or public.normalize_email(auth.jwt() ->> 'email') = client_email_normalized
);

create policy "Allow selected trainer read trainer bookings"
on public.trainer_bookings
for select
to authenticated
using (
  public.current_crm_role() = 'trainer'
  and exists (
    select 1
    from public.crm_users as crm_user
    where crm_user.id = auth.uid()
      and crm_user.role = 'trainer'
      and (
        public.current_crm_email() = public.normalize_email(trainer_bookings.trainer_id)
        or trim(coalesce(crm_user.name, '')) = trainer_bookings.trainer_name
      )
  )
);

create policy "Allow admin read trainer bookings"
on public.trainer_bookings
for select
to authenticated
using (public.current_crm_role() = 'admin');

create policy "Allow admin update trainer bookings"
on public.trainer_bookings
for update
to authenticated
using (public.current_crm_role() = 'admin')
with check (public.current_crm_role() = 'admin');

create policy "Allow selected trainer update trainer booking status"
on public.trainer_bookings
for update
to authenticated
using (
  public.current_crm_role() = 'trainer'
  and exists (
    select 1
    from public.crm_users as crm_user
    where crm_user.id = auth.uid()
      and crm_user.role = 'trainer'
      and (
        public.current_crm_email() = public.normalize_email(trainer_bookings.trainer_id)
        or trim(coalesce(crm_user.name, '')) = trainer_bookings.trainer_name
      )
  )
)
with check (
  public.current_crm_role() = 'trainer'
  and status in ('new', 'in_work', 'processed', 'contacted', 'confirmed', 'cancelled', 'completed')
  and exists (
    select 1
    from public.crm_users as crm_user
    where crm_user.id = auth.uid()
      and crm_user.role = 'trainer'
      and (
        public.current_crm_email() = public.normalize_email(trainer_bookings.trainer_id)
        or trim(coalesce(crm_user.name, '')) = trainer_bookings.trainer_name
      )
  )
);

create policy "Allow admin delete trainer bookings"
on public.trainer_bookings
for delete
to authenticated
using (public.current_crm_role() = 'admin');

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'trainer_bookings'
  ) then
    alter publication supabase_realtime add table public.trainer_bookings;
  end if;
end;
$$;
